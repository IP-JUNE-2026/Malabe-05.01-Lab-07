public class IT26101343Lab7Q2B {
	
		public static void main(String[] args) {
			
			int rowCount;
			int columnCount;
			
			
				
			for (rowCount = 0;rowCount < 5;rowCount++) {
				
				System.out.print((rowCount+1) + "-" );
				
				for(columnCount = 0; columnCount <= rowCount;columnCount++) {
					
					System.out.print("* ");
					
				}
				
			System.out.println();
				
			}
			
			
			
		}
		
}